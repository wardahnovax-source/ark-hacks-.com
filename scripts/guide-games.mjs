export function detectGameFromHost(host) {
	const h = host.toLowerCase();
	for (const [pattern, gameId] of DOMAIN_RULES) {
		if (pattern.test(h)) return gameId;
	}
	return 'ark-ascended';
}

export function getGameMeta(gameId) {
	return GAME_CATALOG[gameId] ?? GAME_CATALOG['ark-ascended'];
}

